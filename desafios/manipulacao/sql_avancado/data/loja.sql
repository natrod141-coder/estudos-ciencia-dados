CREATE TABLE clientes (
    id_cliente    INTEGER PRIMARY KEY,
    nome          TEXT NOT NULL,
    cidade        TEXT NOT NULL,
    estado        TEXT NOT NULL,
    data_cadastro TEXT NOT NULL,  -- data no formato AAAA-MM-DD
    email         TEXT            -- pode ser NULL
);
CREATE TABLE produtos (
    id_produto INTEGER PRIMARY KEY,
    nome       TEXT NOT NULL,
    categoria  TEXT NOT NULL,
    preco      REAL NOT NULL,     -- preço de tabela atual
    ativo      INTEGER NOT NULL   -- 1 = à venda, 0 = fora de linha
);
CREATE TABLE pedidos (
    id_pedido   INTEGER PRIMARY KEY,
    id_cliente  INTEGER NOT NULL REFERENCES clientes (id_cliente),
    data_pedido TEXT NOT NULL,    -- data no formato AAAA-MM-DD
    status      TEXT NOT NULL,    -- 'entregue', 'cancelado' ou 'em trânsito'
    canal       TEXT NOT NULL,    -- 'site', 'app' ou 'telefone'
    frete       REAL NOT NULL
);
CREATE TABLE itens_pedido (
    id_pedido      INTEGER NOT NULL REFERENCES pedidos (id_pedido),
    id_produto     INTEGER NOT NULL REFERENCES produtos (id_produto),
    quantidade     INTEGER NOT NULL,
    preco_unitario REAL NOT NULL, -- preço cobrado na venda (pode ter desconto)
    PRIMARY KEY (id_pedido, id_produto)
);

